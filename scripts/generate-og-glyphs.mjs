/**
 * Extracts glyph outlines from the brand fonts into components/og/glyphs.ts.
 *
 * Why: the share images are rendered by next/og (satori), which cannot use
 * variable fonts or woff2. The brand's display face is Archivo at width 62 /
 * weight 900 — a variable-font instance — so we bake the outlines as SVG
 * paths instead. Re-run after changing fonts or needing new characters:
 *
 *   node scripts/generate-og-glyphs.mjs
 *
 * Fonts in scripts/og-fonts are Latin subsets of OFL-licensed Google Fonts.
 */
import * as fontkit from "fontkit";
import wawoff2 from "wawoff2";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const fontDir = path.join(root, "scripts/og-fonts");

const CHARS = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), "−", "–", "—", "·", "’", "“", "”"];

const FONTS = {
  display: { file: "archivo-latin.woff2", variation: { wdth: 62, wght: 900 } },
  mono: { file: "jetbrains-mono-latin.woff2", variation: { wght: 600 } },
  hand: { file: "caveat-latin.woff2", variation: { wght: 600 } },
  serif: { file: "instrument-serif-italic-latin.woff2" },
};

/** Round path coordinates to integers (font units) to keep the module small. */
const compact = (d) => d.replace(/-?\d*\.?\d+(e-?\d+)?/g, (n) => String(Math.round(Number(n))));

const out = {};
for (const [key, spec] of Object.entries(FONTS)) {
  // fontkit can only instance variable fonts from TTF, so decompress WOFF2 first.
  const ttf = Buffer.from(await wawoff2.decompress(fs.readFileSync(path.join(fontDir, spec.file))));
  const font = fontkit.create(ttf);
  const inst = spec.variation ? font.getVariation(spec.variation) : font;
  const glyphs = {};
  for (const ch of CHARS) {
    const cp = ch.codePointAt(0);
    if (!font.hasGlyphForCodePoint(cp)) continue;
    const g = inst.glyphForCodePoint(cp);
    glyphs[ch] = [Math.round(g.advanceWidth), compact(g.path.toSVG())];
  }
  out[key] = { upm: font.unitsPerEm, ascent: Math.round(font.ascent), descent: Math.round(font.descent), glyphs };
  console.log(`${key}: ${Object.keys(glyphs).length} glyphs`);
}

const banner = `/* Generated by scripts/generate-og-glyphs.mjs — do not edit by hand. */\n`;
const body = `export const OG_FONTS = ${JSON.stringify(out)} as const;\n`;
fs.writeFileSync(path.join(root, "components/og/glyphs.ts"), banner + body);
console.log("wrote components/og/glyphs.ts", ((banner + body).length / 1024).toFixed(0) + " KB");
